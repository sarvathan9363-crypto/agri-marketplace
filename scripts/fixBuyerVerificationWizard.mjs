let content = fs.readFileSync(TARGET_FILE, 'utf8');

for (const item of fileItems) {
  const orig = item.originalText;
  if (!orig || orig.length < 2) continue;

  let key = null;
  for (const [k, v] of Object.entries(localeData.en.buyerVerificationWizard)) {
    if (v === orig) {
      key = k;
      break;
    }
  }

  if (!key) {
    key = textToKey(orig);
    localeData.en.buyerVerificationWizard[key] = orig;
    LOCALES.filter(l => l !== 'en').forEach(l => {
      const trans = dict[orig]?.[l] || orig;
      localeData[l].buyerVerificationWizard[key] = trans;
    });
  }

  const fullKey = `buyerVerificationWizard.${key}`;
  
  if (item.type.startsWith('toast:')) {
    const p = item.type.split(':')[1];
    content = content.replace(`toast.${p}('${orig}')`, `toast.${p}(t('${fullKey}'))`);
    content = content.replace(`toast.${p}("${orig}")`, `toast.${p}(t('${fullKey}'))`);
  } else if (item.type.startsWith('prop:')) {
    const propName = item.type.split(':')[1];
    content = content.replace(`${propName}="${orig}"`, `${propName}={t('${fullKey}')}`);
    content = content.replace(`${propName}='${orig}'`, `${propName}={t('${fullKey}')}`);
  } else if (item.type === 'jsx-text') {
    content = content.replace(`>${orig}<`, `>{t('${fullKey}')}<`);
    content = content.replace(`> ${orig} <`, `>{t('${fullKey}')}<`);
  } else if (item.type === 'ternary') {
    content = content.replace(`'${orig}'`, `t('${fullKey}')`);
    content = content.replace(`"${orig}"`, `t('${fullKey}')`);
  }
}

LOCALES.forEach(l => {
  const p = path.resolve(LOCALES_DIR, l, 'translation.json');
  fs.writeFileSync(p, JSON.stringify(localeData[l], null, 2) + '\n', 'utf8');
});

fs.writeFileSync(TARGET_FILE, content, 'utf8');
