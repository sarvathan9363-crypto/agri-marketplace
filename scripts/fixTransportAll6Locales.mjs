for (const lang of Object.keys(transportTranslations)) {
  const file = path.join(localesDir, lang, 'translation.json');
  if (!fs.existsSync(file)) continue;

  const content = JSON.parse(fs.readFileSync(file, 'utf8'));
  const additions = transportTranslations[lang];

  for (const section of Object.keys(additions)) {
    content[section] = {
      ...(content[section] || {}),
      ...additions[section]
    };
  }

  fs.writeFileSync(file, JSON.stringify(content, null, 2), 'utf8');
  console.log(`Merged expanded transport & auth translations into ${lang}/translation.json`);
}
